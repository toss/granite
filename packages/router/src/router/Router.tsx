import {
  createNavigationContainerRef,
  NavigationContainer,
  NavigationIndependentTree,
  type NavigationContainerRefWithCurrent,
  type ParamListBase,
  type RouteProp,
} from '@granite-js/native/@react-navigation/native';
import type {
  NativeStackNavigationOptions,
  NativeStackOptionsArgs,
} from '@granite-js/native/@react-navigation/native-stack';
import { SafeAreaProvider } from '@granite-js/native/react-native-safe-area-context';
import { type ComponentProps, type ComponentType, type PropsWithChildren, useCallback, useMemo, useState } from 'react';
import { BackEventProvider } from '../use-back-event';
import { RouterActivityProvider } from '../visibility/useVisibility';
import { BackButton } from './components/BackButton';
import { CanGoBackGuard, type SetIOSBackPressHandler } from './components/CanGoBackGuard';
import { StackNavigator } from './components/StackNavigator';
import { useInternalRouterBackHandler } from './components/useRouterBackHandler';
import { useRouterControls, type RouterControlsConfig } from './hooks/useRouterControls';
import type { ErrorComponent, RequireContext } from './types';
import { BASE_STACK_NAVIGATOR_STYLE } from './types/screen-option';

type LegacyScreenOptions =
  | NativeStackNavigationOptions
  | ((props: { route: RouteProp<ParamListBase>; navigation: any }) => NativeStackNavigationOptions);

export interface RouterScreenOptionsArgs extends NativeStackOptionsArgs<ParamListBase> {
  /** Zero-based position of this route in the stack, not the focused index. -1 when not in the stack yet. */
  routeIndex: number;
  /** Runs registered back handlers before going back or invoking onRootBack if no history remains. */
  onBack: () => void;
}

export type RouterScreenOptions =
  | NativeStackNavigationOptions
  | ((props: RouterScreenOptionsArgs) => NativeStackNavigationOptions);

type ScreenOptionsConfig =
  | {
      /** Default options for all screens. The callback can customize options by routeIndex. */
      defaultScreenOptions?: RouterScreenOptions;
      /** @deprecated Use defaultScreenOptions instead. */
      defaultScreenOption?: never;
    }
  | {
      defaultScreenOptions?: never;
      /** @deprecated Use defaultScreenOptions instead. Retains the original callback arguments. */
      defaultScreenOption?: LegacyScreenOptions;
    };

export type RouterProps = StackNavigatorProps &
  NavigationContainerProps &
  ScreenOptionsConfig & {
    /** Override AppState with the host activity state. False disables back handlers. */
    isActive?: boolean;
    /** File-based route modules, generated by the router build plugin. */
    context: RequireContext;
    /** URL prefix owned by this router, for example example://app. */
    prefix: string;
    /** Entry URL. Read on mount; later prop updates do not navigate or reset the stack. */
    initialUrl?: string;
    /** Optional initial URL resolver, supplied by the app or host adapter. */
    getInitialUrl?: RouterControlsConfig['getInitialUrl'];
    /** Called after back handlers allow leaving a stack with no previous screen. */
    onRootBack?: () => void;
    /** Host gesture integration; omitted for standalone apps. */
    setIosSwipeGestureEnabled?: ({ isEnabled }: { isEnabled: boolean }) => Promise<void> | void;
    setiOSBackPressHandler?: SetIOSBackPressHandler;
  };

interface StackNavigatorProps {
  /**
   * @name navigationContainerRef
   * @description
   * You can create and pass a NavigationContainerRef from @react-navigation/native externally. This allows external control of the router.
   */
  navigationContainerRef?: NavigationContainerRefWithCurrent<never>;
  /**
   * @name screenContainer
   * @description
   * Container component that wraps each Screen component.
   */
  screenContainer?: ComponentType<PropsWithChildren<any>>;
  /**
   * @name defaultErrorComponent
   * @description
   * Error boundary component used when a route does not provide its own error component.
   */
  defaultErrorComponent?: ErrorComponent;
}

type NavigationContainerProps = Pick<
  ComponentProps<typeof NavigationContainer>,
  'theme' | 'documentTitle' | 'fallback' | 'onReady' | 'onUnhandledAction' | 'onStateChange' | 'initialState'
>;

/**
 * A standalone file-based router. Render it below app providers to use their values
 * in defaultScreenOptions. Options callbacks compute values; call hooks in the
 * parent component, never inside an options callback.
 */
export function Router({ isActive, ...props }: RouterProps) {
  return (
    <NavigationIndependentTree>
      <RouterActivityProvider isActive={isActive}>
        <SafeAreaProvider>
          <BackEventProvider>
            <RouterNavigator {...props} />
          </BackEventProvider>
        </SafeAreaProvider>
      </RouterActivityProvider>
    </NavigationIndependentTree>
  );
}

function RouterNavigator({
  prefix,
  context,
  initialUrl,
  getInitialUrl,
  onRootBack,
  navigationContainerRef,
  defaultScreenOptions,
  defaultScreenOption,
  screenContainer,
  defaultErrorComponent,
  setIosSwipeGestureEnabled,
  setiOSBackPressHandler,
  onReady,
  onStateChange,
  ...navigationContainerProps
}: RouterProps) {
  const { Screens, linkingOptions } = useRouterControls({
    prefix,
    context,
    screenContainer,
    initialUrl,
    getInitialUrl,
    defaultErrorComponent,
  });
  const ref = useMemo(() => navigationContainerRef ?? createNavigationContainerRef<never>(), [navigationContainerRef]);
  const { handler, handleBackEvent, canGoBack, hasBackEvent } = useInternalRouterBackHandler({
    navigationContainerRef: ref,
    onClose: onRootBack,
  });
  const headerLeft = useCallback(
    (props: Parameters<NonNullable<NativeStackNavigationOptions['headerLeft']>>[0]) =>
      props.canGoBack || onRootBack != null ? <BackButton {...props} onPress={handler} /> : null,
    [handler, onRootBack]
  );
  const screenOptions = useCallback(
    (screenProps: NativeStackOptionsArgs<ParamListBase>) => ({
      ...BASE_STACK_NAVIGATOR_STYLE,
      gestureEnabled: canGoBack,
      headerLeft,
      ...(defaultScreenOptions !== undefined
        ? typeof defaultScreenOptions === 'function'
          ? defaultScreenOptions({
              ...screenProps,
              routeIndex: screenProps.navigation
                .getState()
                .routes.findIndex((route) => route.key === screenProps.route.key),
              onBack: handler,
            })
          : defaultScreenOptions
        : typeof defaultScreenOption === 'function'
          ? defaultScreenOption(screenProps)
          : defaultScreenOption),
    }),
    [canGoBack, defaultScreenOptions, defaultScreenOption, headerLeft, handler]
  );
  const [isInitialScreen, setIsInitialScreen] = useState((navigationContainerProps.initialState?.index ?? 0) === 0);

  return (
    <NavigationContainer
      {...navigationContainerProps}
      ref={ref}
      linking={linkingOptions}
      onReady={() => {
        setIsInitialScreen((ref.getRootState()?.index ?? 0) === 0);
        onReady?.();
      }}
      onStateChange={(state) => {
        setIsInitialScreen((state?.index ?? 0) === 0);
        onStateChange?.(state);
      }}
    >
      <CanGoBackGuard
        canGoBack={canGoBack}
        hasBackEvent={hasBackEvent}
        isInitialScreen={isInitialScreen}
        hasRootBackAction={onRootBack != null}
        onBack={handleBackEvent}
        setIosSwipeGestureEnabled={setIosSwipeGestureEnabled}
        setiOSBackPressHandler={setiOSBackPressHandler}
      >
        <StackNavigator.Navigator screenOptions={screenOptions}>{Screens}</StackNavigator.Navigator>
      </CanGoBackGuard>
    </NavigationContainer>
  );
}
